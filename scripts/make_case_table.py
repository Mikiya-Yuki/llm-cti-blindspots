"""Assemble pilot/case_table.md and case_table.csv from frozen inputs, ATT&CK refs, and verified answer keys.
Usage: python3 -I make_case_table.py <pilot_dir> <parsed_summary_json>"""
import sys, os, json, csv, hashlib, re
P = sys.argv[1]; summ = {r['case_id']: r for r in json.load(open(sys.argv[2]))}
CASES = [
 ('AA23-270A','CN','S1','2023-09-27','—'),
 ('AA23-347A','RU','S1','2023-12-13','—'),
 ('AA23-335A','NK/IR (IR)','S1','2023-12-01','2023-12-14; 2024-12-18'),
 ('AA23-325A','FIN','S1','2023-11-21','—'),
 ('AA24-190A','CN','S2','2024-07-08','—'),
 ('AA24-249A','RU','S2','2024-09-05','—'),
 ('AA24-207A','NK/IR (NK)','S2','2024-07-25','2024-08-06†'),
 ('AA24-242A','FIN','S2','2024-08-29','—'),
 ('AA26-281A','CN','S3','2026-10-08','—'),
 ('AA26-194A','RU','S3','2026-07-13','—'),
 ('AA26-097A','NK/IR (IR)','S3','2026-04-07','2026-07-22'),
 ('AA26-222A','FIN','S3','2026-08-10','—'),
]
SD = {'AA23-270A':('S1','D1'),'AA23-347A':('S2','D2'),'AA23-335A':('S2','D1'),'AA23-325A':('S0','D0'),
      'AA24-190A':('S2','D2'),'AA24-249A':('S2','D2'),'AA24-207A':('S2','D2'),'AA24-242A':('S0','D0'),
      'AA26-281A':('S1','D1'),'AA26-194A':('S2','D2'),'AA26-097A':('S1','D1'),'AA26-222A':('S0','D0')}
snap = dict(l.split()[::-1] for l in open(os.path.join(P,'snapshots','SHA256SUMS.txt')) if l.strip())
rows=[]
for cid,grp,st,rel,rev in CASES:
    c=cid.lower()
    inp=open(os.path.join(P,'inputs',c+'_input.txt'),encoding='utf-8').read()
    ref=json.load(open(os.path.join(P,'attack_refs',c+'_attack_ref.json')))
    keyp=os.path.join(P,'answer_keys',c+'_key.json')
    key=json.load(open(keyp)) if os.path.exists(keyp) else {}
    def n(field, core=None):
        v=key.get(field,[]) or []
        return sum(1 for x in v if core is None or x.get('core')==core)
    prim=[a['name'] for a in key.get('actor_designations',[]) if a.get('kind')=='primary']
    aliases=[a['name'] for a in key.get('actor_designations',[]) if a.get('kind')!='primary']
    MAIN = {'AA24-190A':'assess that this group conduct','AA26-194A':'Center 16 cyber actors continue to exploit',
            'AA24-207A':'is a North Korean state-sponsored cyber group','AA26-097A':'assess a group of Iranian-affiliated APT actors',
            'AA24-249A':'are responsible for computer network operations','AA23-347A':'assess Russian Foreign Intelligence Service'}
    sts = key.get('attribution_statements',[]) or []
    main_att = next((x['quote'] for x in sts if MAIN.get(cid,'\x00') in x['quote']), sts[0]['quote'] if sts else '')
    legacy=sorted({f"{x['id']}→{x.get('replaced_by')}" for x in ref['inline_ids']+ref['table_ids'] if x['status']!='active'})
    rows.append(dict(
        case_id=cid, group=grp, stratum=st, title=summ[cid]['title'], url=summ[cid]['url'],
        released=rel, revised=rev, retrieved='2026-11-19',
        authoring_agencies='; '.join(a['name'] for a in key.get('authoring_agencies',[])),
        actor_primary='; '.join(prim), actor_other='; '.join(aliases),
        attribution_code=key.get('attribution_strength_code',''), attr_specificity=SD[cid][0], attr_directness=SD[cid][1], attribution_rationale=key.get('attribution_strength_rationale',''),
        attribution_main_quote=main_att,
        input_words=len(re.findall(r"[A-Za-z0-9][A-Za-z0-9'\-\.]*", inp)),
        input_sha256=hashlib.sha256(inp.encode('utf-8')).hexdigest(),
        snapshot_sha256=snap.get(c+'_20261119.html',''),
        n_malware_tools=f"{n('malware_tools',True)}/{n('malware_tools')}", n_cves=f"{n('vulnerabilities',True)}/{n('vulnerabilities')}",
        n_products=f"{n('affected_products_or_technologies',True)}/{n('affected_products_or_technologies')}",
        n_sectors=f"{n('target_sectors',True)}/{n('target_sectors')}", n_regions=f"{n('target_regions',True)}/{n('target_regions')}",
        n_dates=f"{n('dates',True)}/{n('dates')}",
        attack_inline=ref['n_inline'], attack_table_only=len({x['id'] for x in ref['table_ids']}-{x['id'] for x in ref['inline_ids']}),
        attack_legacy='; '.join(legacy) if legacy else '—'))
with open(os.path.join(P,'case_table.csv'),'w',newline='',encoding='utf-8') as f:
    w=csv.DictWriter(f,fieldnames=list(rows[0].keys())); w.writeheader(); w.writerows(rows)
print('wrote', len(rows), 'rows')

# ---------- markdown rendering ----------
from statistics import mean
def short(s, n=70): return s if len(s)<=n else s[:n-1]+'…'
md=[]
md.append('# Pilot case table — 12 public advisories (frozen 2026-11-19)\n')
md.append('Generated by `scripts/make_case_table.py` from the frozen inputs, ATT&CK references, and answer keys. Full fields: `case_table.csv`.\n')
md.append('- **Document type:** CISA-hosted joint cybersecurity advisories (AA series). All cases are government advisories; no vendor reports.')
md.append('- **Design:** 4 groups (CN / RU / NK·IR / FIN) × 3 strata (S1 = Sep–Dec 2023, S2 = Jul–Sep 2024, S3 = Apr–Oct 2026).')
md.append('- **Snapshot:** HTML retrieved 2026-11-19 (`snapshots/`). Model input = narrative sections only, with inline ATT&CK technique IDs, MITRE software/group/tactic IDs, and citation markers removed (`inputs/`).')
md.append('- **ATT&CK:** Enterprise v20.1 (STIX sha256 539a843a7b53ed97…) and ICS v20.1 (STIX sha256 3f6448369f9135ad…), released 2026-11-05.')
md.append('- **Attribution codes** (codebook §3.6): S = entity specificity (S0 none, S1 country/government, S2 named organ/unit); D = link directness (D0 none, D1 indirect, D2 direct). A3 = S2+D2, A2 = S1+D2, A1 = D1 at any specificity, A0 = D0. They describe the source\'s claim, not its truth.')
md.append('- **Item counts** are shown as core/all, from the answer keys. "ATT&CK inline" = IDs the source attached to narrative sentences (primary reference); "table-only" = IDs that appear only in appendix tables (secondary reference).\n')
md.append('## Overview\n')
md.append('| Stratum | Group | Case | Title | Released (revised) | Input words | Attr. (S/D) | Primary actor designation | Tools | CVEs | Sectors | Regions | Dates | ATT&CK inline / table-only |')
md.append('|---|---|---|---|---|---|---|---|---|---|---|---|---|---|')
for r in rows:
    rev = '' if r['revised']=='—' else f" (rev. {r['revised']})"
    md.append(f"| {r['stratum']} | {r['group']} | [{r['case_id']}]({r['url']}) | {short(r['title'])} | {r['released']}{rev} | {r['input_words']} | {r['attribution_code'] or '?'} ({r['attr_specificity']}/{r['attr_directness']}) | {short(r['actor_primary'] or '?',40)} | {r['n_malware_tools']} | {r['n_cves']} | {r['n_sectors']} | {r['n_regions']} | {r['n_dates']} | {r['attack_inline']} / {r['attack_table_only']} |")
md.append('\n## Matching check\n')
groups={}
for r in rows: groups.setdefault(r['group'].split(' ')[0],[]).append(r)
md.append('| Group | Mean input words | Range | Attribution codes |')
md.append('|---|---|---|---|')
for g,rs in groups.items():
    w=[x['input_words'] for x in rs]
    md.append(f"| {g} | {round(mean(w))} | {min(w)}–{max(w)} | {', '.join(x['attribution_code'] or '?' for x in rs)} |")
md.append('\nDeviations to report: input length is not balanced (CN cases are longest). AA23-335A (revised 2024-12-18) and AA26-097A (revised 2026-07-22) are used in their revised versions as of the snapshot. AA24-207A carries a 2024-08-06 update in its version history (†; the page itself shows only the release date). Attribution strength is not balanced across groups: all RU cases are A3, CN and NK/IR mix A1 and A3, and FIN cases are A0 by design. Compare attribution-fidelity rates within the same starting level (codebook §3.6).\n')
md.append('## ATT&CK IDs revoked in v20.1 (scored as legacy-valid)\n')
for r in rows:
    if r['attack_legacy']!='—': md.append(f"- {r['case_id']}: {r['attack_legacy']}")
md.append('\n## Per-case details\n')
for r in rows:
    md.append(f"### {r['case_id']} — {r['title']}\n")
    md.append(f"- Group / stratum: {r['group']} / {r['stratum']}; released {r['released']}; revised {r['revised']}; retrieved {r['retrieved']}")
    md.append(f"- URL: {r['url']}")
    md.append(f"- Authoring agencies (as listed in the input): {r['authoring_agencies'] or '?'}")
    md.append(f"- Actor designations: primary = {r['actor_primary'] or '?'}; other = {r['actor_other'] or '—'}")
    md.append(f"- Attribution code: **{r['attribution_code'] or '?'}** ({r['attr_specificity']}/{r['attr_directness']}) — {r['attribution_rationale']}")
    md.append(f"- Main attribution statement (verbatim): \"{r['attribution_main_quote']}\"")
    md.append(f"- Input: {r['input_words']} words; sha256 {r['input_sha256'][:16]}…; snapshot sha256 {r['snapshot_sha256'][:16]}…")
    md.append(f"- ATT&CK reference: {r['attack_inline']} inline IDs, {r['attack_table_only']} table-only IDs; legacy: {r['attack_legacy']}\n")
md.append('## Case-specific scoring notes\n')
for a,b in [
 ('AA23-347A','The input includes the VICTIM TYPES paragraph (regions and victim types), which the agencies call opportunistic rather than targeted. SolarWinds, WellMess/WellMail/Sorefang and Diplomatic Orbiter are historical context and keyed as non-core.'),
 ('AA23-335A / AA26-097A','AA23-335A calls CyberAv3ngers a persona of IRGC-affiliated actors. AA26-097A mentions CyberAv3ngers only for previously reported similar activity and never says it conducted the current activity. Each key follows its own text.'),
 ('AA24-190A','CVE-2021-31207 is listed under two products and keyed once. Case study 2 names no CVE or product.'),
 ('AA24-207A','The source misspells one ID as "CEV-2021-43207"; credit either CVE-2021-43207 or the misspelling. The 45 CVEs are introduced as researched by the actors, so only Log4j is core.'),
 ('AA24-242A','The nine CVE IDs were restored after an extraction fix; the text does not tie CVE-2020-1472 to the name "Zerologon".'),
 ('AA24-249A','Five CVEs were obtained but not exploited, so they are non-core. "Efforts to provide aid to Ukraine" is keyed as a core target because the text calls it the primary focus.'),
 ('AA26-281A','The CVE IDs exist only in Appendix B, which is excluded from the input. Any CVE in an output therefore comes from outside the input (UA). Flax Typhoon and its other names appear only as "TTPs consistent with", so a model that equates them with Integrity Tech is upgrading the claim.'),
 ('AA26-194A','There are no calendar dates, and the text does not say which product each CVE affects.'),
 ('AA26-222A','"KPNA" in the source is a typo for KNPA. Conti is malware lineage, not attribution.'),
]:
    md.append(f'- **{a}:** {b}')
md.append('')
md.append('## Candidates considered and excluded\n')
md.append('| Advisory | Reason |')
md.append('|---|---|')
for a,b in [
 ('AA24-038A (PRC / Volt Typhoon, 2024-02)','Narrative about 5,000 words, far longer than the matched RU/FIN cases.'),
 ('AA23-144A (PRC / Volt Typhoon LOTL, 2023-05)','Outside the S1 window (Sep–Dec 2023), which is set by the RU and IR cases; AA23-270A falls inside it.'),
 ('AA25-239A (PRC / Salt Typhoon, 2025-08)','About 4,200 words, and the candidate search found no 2025 NK/IR AA-series advisory to complete a 2025 stratum.'),
 ('AA23-129A (FSB / Snake, 2023-05)','About 10,600 words.'),
 ('AA26-204A (Russian state-supported / Zimbra, 2026-07)','About 5,300 words; AA26-194A was used for RU-S3.'),
 ('AA23-320A, AA23-352A, AA24-109A, AA24-131A, AA25-071A (ransomware)','Substantially revised after release (new TTPs added), which blurs the publication period.'),
 ('AA25-050A (Ghost ransomware, 2025-02)','States that the financially motivated actors are located in China. This would add a country cue to the FIN group; keep it for a later contrast.'),
 ('AA26-251A (China-based AI companies / distillation, 2026-09)','Not an intrusion advisory, and it concerns Chinese AI developers themselves (a self-referential confound for Chinese models). Keep it for a separate probe.'),
 ('AA26-113A (China-nexus covert networks, 2026-04)','Guidance-type document with only 4 ATT&CK IDs; AA26-281A was used for CN-S3.'),
]:
    md.append(f'| {a} | {b} |')
open(os.path.join(P,'case_table.md'),'w',encoding='utf-8').write('\n'.join(md)+'\n')
print('wrote case_table.md')
